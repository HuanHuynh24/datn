// Requires scripts/serve_cv_browser_api.py: all API traffic goes to rollback-only test port8001.
// Credentials are read from the existing ignored local file, never logged.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { withBrowser } from './browser-consumer.mjs';
const env = Object.fromEntries(fs.readFileSync(new URL('../../.env.cv-browser', import.meta.url), 'utf8').split(/\r?\n/).filter(line => line && !line.startsWith('#')).map(line => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i + 1)]; }));
const checks = [];
await withBrowser(null, async ({ send, evaluate, until, fill, click, requests, responses }) => {
  const follow = async href => {
    if (!await evaluate(`!!document.querySelector('a[href="${href}"]')`)) await evaluate(`document.querySelector('.site-menu-toggle').click()`);
    await until(`!!document.querySelector('a[href="${href}"]')`); await evaluate(`document.querySelector('a[href="${href}"]').click()`);
  };
  const login = async employer => {
    await send('Page.navigate', { url: 'http://localhost:3000/sign-in?audience=' + (employer ? 'recruiter' : 'candidate') });
    await until(`(()=>{const form=document.querySelector('form');return form&&Object.keys(form).some(key=>key.startsWith('__reactProps')&&typeof form[key].onSubmit==='function')})()`);
    const prefix = employer ? 'EMPLOYER' : 'CANDIDATE';
    await fill('#auth-email', env['BROWSER_' + prefix + '_EMAIL']); await fill('#auth-password', env['BROWSER_' + prefix + '_PASSWORD']);
    await evaluate('document.querySelector("form").requestSubmit()');
    await until('location.pathname===' + JSON.stringify(employer ? '/recruiter' : '/candidate'));
  };
  await login(false); await follow('/candidate/profile');
  await click('Chỉnh sửa thông tin'); await until('!!document.querySelector("#profile-province")');
  const provinceId = await evaluate(`document.querySelector('#profile-province option[value]:not([value=""])').value`);
  await evaluate(`(()=>{const select=document.querySelector('#profile-province');select.value=${JSON.stringify(provinceId)};select.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await fill('#profile-work-type', 'Full-time'); await fill('#profile-avatar', 'https://example.com/avatar.png');
  await click('Thêm học vấn'); await fill('#education-0', 'MySQL Browser University');
  await click('Thêm kinh nghiệm'); await fill('#experience-0', 'MySQL Browser Engineer');
  await click('Lưu thay đổi'); await until('!document.querySelector("dialog")&&document.body.innerText.includes("MySQL Browser University")');
  checks.push('Profile province/work-type/avatar/history PATCH to MySQL');
  await login(false); await follow('/candidate/profile');
  await until('document.body.innerText.includes("MySQL Browser Engineer")');
  checks.push('Profile extended fields persisted after fresh login');
  const tokenResponse = await fetch('http://localhost:8001/api/v1/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: env.BROWSER_CANDIDATE_EMAIL, password: env.BROWSER_CANDIDATE_PASSWORD }) });
  assert(tokenResponse.ok);
  const token = (await tokenResponse.json()).access_token;
  const profileHeaders = { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' };
  const legacyEducation = [{ school: 'Legacy University', preserved: { graduation: 2020 } }];
  const legacyExperience = { records: [{ employer: 'Legacy Company' }] };
  const seeded = await fetch('http://localhost:8001/api/v1/candidates/me/profile', { method: 'PATCH', headers: profileHeaders, body: JSON.stringify({ education: legacyEducation, experience: legacyExperience }) });
  assert(seeded.ok);
  await login(false); await follow('/candidate/profile'); await click('Chỉnh sửa thông tin');
  await until('document.querySelector("dialog")?.innerText.includes("Legacy University")');
  assert.equal(await evaluate('!!document.querySelector("#education-0")'), false);
  await fill('#profile-phone', '0123456789'); await click('Lưu thay đổi');
  await until('!document.querySelector("dialog")&&document.body.innerText.includes("0123456789")');
  const persisted = await (await fetch('http://localhost:8001/api/v1/candidates/me/profile', { headers: profileHeaders })).json();
  assert.deepEqual(persisted.education, legacyEducation); assert.deepEqual(persisted.experience, legacyExperience);
  checks.push('Legacy JSON objects remain unchanged when editing other fields');
  await click('Chỉnh sửa thông tin'); await fill('#profile-minimum', '2000'); await fill('#profile-maximum', '1000'); await click('Lưu thay đổi');
  await until('!!document.querySelector("dialog [role=alert]")');
  assert(await evaluate('!!document.querySelector("#profile-name")'));
  await click('Hủy');
  checks.push('Invalid salary range rejected by MySQL-backed Backend without fake success');
  await follow('/candidate/cvs');
  await until('!!document.querySelector("#cv-file")&&!document.body.innerText.includes("Đang tải CV…")');
  await evaluate(`(()=>{const input=document.querySelector('#cv-file');const data=new DataTransfer();data.items.add(new File(['%PDF-1.7\\nE8 MySQL browser CV\\n%%EOF'],'resume.pdf',{type:'application/pdf'}));input.files=data.files;input.dispatchEvent(new Event('change',{bubbles:true}));document.querySelector('form').requestSubmit();})()`);
  await until('document.body.innerText.includes("Đã tải CV lên.")');
  await click('Xem CV đã lưu');
  await until('!document.querySelector("dialog[open]")');
  await click('Đặt mặc định');
  await until('document.body.innerText.includes("Bỏ CV chính")');
  checks.push('Private CV upload and primary against MySQL');
  await follow('/jobs'); await until('!!document.querySelector("[data-job-id]")');
  const jobId = await evaluate('document.querySelector("[data-job-id]").dataset.jobId');
  const title = await evaluate('document.querySelector(".cl-job-title button").textContent');
  const actualJob = await (await fetch('http://localhost:8001/api/v1/jobs/' + jobId)).json();
  await evaluate(`([...document.querySelectorAll('.cl-filter-trigger')].find(button=>button.textContent.includes('Tỉnh/thành'))).click()`);
  await until('!!document.querySelector("input[name=province_id][value]")');
  await evaluate(`document.querySelector('input[name="province_id"][value="${actualJob.province_id}"]').click()`);
  await evaluate(`document.querySelector('input[name="province_id"]').closest('form').requestSubmit()`);
  await until('location.search.includes("province_id=")&&!!document.querySelector("[data-job-id]")');
  await fill('input[aria-label="Từ khóa tìm việc"]', title); await evaluate('document.querySelector(".cl-results-mobile-search").requestSubmit()');
  await until('location.search.includes("keyword=")&&!!document.querySelector("[data-job-id]")');
  assert(requests.some(item => item.path === '/api/v1/jobs' && new URLSearchParams(item.query).get('q') === title && new URLSearchParams(item.query).has('province_id')));
  checks.push('Jobs keyword and catalog province filter reach MySQL through UI');
  await evaluate('document.querySelector(".cl-job-title button").click()'); await until('!!document.querySelector("#apply-cv")');
  await fill('#cover-letter', 'E8 MySQL application'); await click('Nộp hồ sơ');
  await until('document.body.innerText.includes("Đã nộp hồ sơ.")');
  checks.push('Public Jobs and apply with real MySQL IDs');
  await follow('/candidate/applications'); await until('!![...document.querySelectorAll("button")].find(button=>button.textContent.startsWith("Chi tiết đơn #"))');
  await evaluate(`[...document.querySelectorAll('button')].find(button=>button.textContent.startsWith('Chi tiết đơn #')).click()`);
  await until('!!document.querySelector("dialog")&&document.querySelector("dialog").innerText.includes("E8 MySQL application")');
  assert(responses.some(item => /^\/api\/v1\/applications\/[0-9]+$/.test(item.path) && item.status === 200));
  checks.push('Candidate detail scoped by Backend MySQL');
  await login(true); await follow('/recruiter/applicants');
  await until('!![...document.querySelectorAll("button")].find(button=>button.textContent.startsWith("Chi tiết đơn #"))');
  await evaluate(`[...document.querySelectorAll('button')].find(button=>button.textContent.startsWith('Chi tiết đơn #')).click()`);
  await until('!!document.querySelector("dialog")&&document.querySelector("dialog").innerText.includes("E8 MySQL application")');
  for (const text of ['Đang xem xét', 'Phỏng vấn', 'Đề nghị tuyển dụng', 'Đã tuyển']) {
    await click(text); await click('Xác nhận trạng thái đơn');
    await until('!document.body.innerText.includes("Xác nhận chuyển từ")&&document.querySelector("dialog").innerText.includes('+JSON.stringify(text)+')');
  }
  checks.push('Employer confirmed transitions through HIRED in MySQL');
  await evaluate('document.querySelector("dialog button[aria-label]").click()');
  await follow('/recruiter/pipeline');
  await click('Đã tuyển'); await until('location.search.includes("status=HIRED")&&!document.body.innerText.includes("Đang tải đơn ứng tuyển")');
  assert(await evaluate('document.body.innerText.includes("Chi tiết đơn #")'));
  checks.push('Pipeline HIRED filter reads actual MySQL state');
  await login(false); await follow('/candidate/cvs');
  await until('document.body.innerText.includes("Lưu trữ")'); await click('Lưu trữ');
  await until('document.body.innerText.includes("Chưa có CV hoạt động")');
  await follow('/candidate/applications'); await until('document.body.innerText.includes("Đã tuyển")');
  await click('Tải CV đã nộp');
  for (let i = 0; i < 100 && !responses.some(item => item.path.endsWith('/cv') && item.status === 200); i++) await new Promise(resolve => setTimeout(resolve, 100));
  assert(responses.some(item => item.path.endsWith('/cv') && item.status === 200));
  checks.push('Application snapshot download survives source CV archive');
  assert(requests.some(item => item.path === '/api/v1/jobs' && new URLSearchParams(item.query).get('limit') === '15'));
  assert(requests.some(item => item.path === '/api/v1/companies/me/applications' && new URLSearchParams(item.query).get('status') === 'HIRED'));
  assert(jobId);
}, { mysqlTest: true });
console.log(JSON.stringify({ status: 'PASS', api: 'localhost:8001 rollback-only MySQL fixture', checks }, null, 2));
